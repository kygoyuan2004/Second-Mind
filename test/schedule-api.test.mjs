import test from 'node:test';
import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import fs from 'node:fs/promises';
import path from 'node:path';
import { sdkApplication } from './sdk-test-helpers.mjs';
import { StudyPlanStore } from '../src/original/study-plan-store.mjs';

test('plan preview, confirmed write, receipt replay and per-event conflict through the authenticated API', async t => {
  const { app, call } = await sdkApplication(t);
  const { store, config } = app.knowledgeBaseHub.resolve('default');
  const date = '2026-11-20';
  const content = '# ' + date + ' 计划\n\n- [ ] 09:00–10:00 阅读公开笔记\n';
  const prepared = await store.prepareDatedDocument('plan', date);
  const draft = await store.createDraft({ userId: 'admin', kind: 'plan', content, date, prepared });
  const endpoint = '/api/knowledge/drafts/' + draft.id;
  const post = (url, data) => call(url, { method: 'POST', body: JSON.stringify(data) });
  const response = await post(endpoint + '/schedule-preview', { content });
  assert.equal(response.status, 200);
  const preview = await response.json();
  assert.equal(preview.candidates.length, 1);
  const body = { content: preview.content, items: preview.candidates, previewId: preview.id, operationId: crypto.randomUUID() };
  const confirmed = await Promise.all([post(endpoint + '/save', body), post(endpoint + '/save', body)]);
  for (const r of confirmed) assert.equal(r.status, 200);
  const [first, second] = await Promise.all(confirmed.map(r => r.json()));
  assert.deepEqual(first, second);
  assert.equal(first.schedule.added, 1);
  assert.equal(await fs.readFile(path.join(store.root, first.path), 'utf8'), content);
  const restarted = new StudyPlanStore({ root: path.join(config.dataDir, 'study-plans'), knowledgeStore: store });
  await restarted.ready;
  assert.equal((await restarted.retry('admin', body.operationId)).path, first.path);
  assert.equal((await store.saveDraft('admin', draft.id, { content, operationId: body.operationId })).path, first.path);
  const state = await (await call('/api/knowledge/schedule/state')).json();
  assert.equal(state.events.length, 1);
  const event = { ...state.events[0], done: true };
  assert.equal((await post('/api/knowledge/schedule/events', { event, expectedRevision: event.revision })).status, 200);
  assert.equal((await post('/api/knowledge/schedule/events', { event, expectedRevision: event.revision })).status, 409);
  assert.equal((await call('/api/knowledge/schedule/state?knowledgeBaseId=missing')).status, 404);
});
